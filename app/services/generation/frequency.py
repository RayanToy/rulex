"""Частотность слова: высокая, средняя, низкая.

От неё зависит состав теста (около 70% частотных слов и 30% редких)
и уровень ученика: высокий требует владения редкими словами. Раньше
метки раздавались по заранее перемешанному списку — случайно,
независимо от слова: «свояченица» получала «высокую» частотность,
«спецэффект» — «низкую».

Мера — словарь Шарова (частота в ipm по Национальному корпусу русского
языка). Абсолютные пороги здесь не работают: списки по классам — это
новые для класса слова, и почти все они в языке редкие. Среди слов,
которые подтверждают словари, частоту от 10 ipm имеют 1–6%, а в словаре
Шарова вообще нет от 29% (4 класс) до 68% (7 класс). Поэтому деление
относительное, внутри пула кандидатов класса:

- низкая — слова нет в частотном словаре;
- высокая и средняя — выше и ниже медианной частоты остальных кандидатов.
"""
import statistics

HIGH, MEDIUM, LOW = "high", "medium", "low"


def frequency_bands(words: list[str], word_manager) -> dict[str, str]:
    """Полоса частотности для каждого слова пула."""
    ipm = {w: word_manager.get_sharov_frequency(w) for w in words}
    known = [v for v in ipm.values() if v > 0]
    median = statistics.median(known) if known else 0.0
    return {w: LOW if v <= 0 else (HIGH if v >= median else MEDIUM) for w, v in ipm.items()}
